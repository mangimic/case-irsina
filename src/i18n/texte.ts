export const TEXTE: Record<Sprache, Satz> = { it, en, de, nl, fr };

/**
 * Text in der gewuenschten Sprache. Platzhalter der Form {name} werden ersetzt:
 *   t('de', 'mapPending', { n: 3 })  ->  "Fuer 3 Objekte sind noch ..."
 */
export function t(
  lang: Sprache,
  schluessel: TextSchluessel,
  werte?: Record<string, string | number>,
): string {
  let text: string = TEXTE[lang][schluessel];
  if (werte) {
    for (const [name, wert] of Object.entries(werte)) {
      text = text.replaceAll(`{${name}}`, String(wert));
    }
  }
  return text;
}

/** Bequemer Zugriff innerhalb einer Seite: const tt = uebersetzer(lang). */
export function uebersetzer(lang: Sprache) {
  return (schluessel: TextSchluessel, werte?: Record<string, string | number>) =>
    t(lang, schluessel, werte);
}
